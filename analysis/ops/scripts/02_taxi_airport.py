import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
from common import *
df = base()
print("filter: clean = 60 <= TAXITIME_SEC <= 14400;  excluded:", df.filter(~pl.col("clean")).height, "of", df.height)
c = df.filter("clean")
t = c.group_by("APT","PHASE_mvt").agg(stats()).sort("PHASE_mvt","median", descending=[False,True])
print(t)
print("ALL airports:"); print(c.group_by("PHASE_mvt").agg(stats()))
w = t.pivot(on="PHASE_mvt", index="APT", values="median").sort("DEP", descending=True)
print(w)
# chart: box-ish bar with median and p90
dep = t.filter(pl.col("PHASE_mvt")=="DEP").sort("median"); arr = t.filter(pl.col("PHASE_mvt")=="ARR")
arr = dep.select("APT").join(arr, on="APT", how="left")
fig, ax = plt.subplots(figsize=(9,5.5))
y = range(len(dep))
ax.barh([i+0.2 for i in y], dep["median"], height=0.4, color="#2b6cb0", label="Taxi-out, median")
ax.barh([i-0.2 for i in y], arr["median"], height=0.4, color="#9ac1e8", label="Taxi-in, median")
ax.scatter(dep["p90"], [i+0.2 for i in y], marker="|", s=120, color="#1a365d", label="Taxi-out, p90")
ax.scatter(arr["p90"], [i-0.2 for i in y], marker="|", s=120, color="#4a7fb5", label="Taxi-in, p90")
for i,(m) in enumerate(dep["median"]): ax.text(m+0.2, i+0.2, f"{m:.1f}", va="center", fontsize=8)
ax.set_yticks(list(y)); ax.set_yticklabels(dep["APT"]); ax.set_xlabel("minutes")
ax.set_title("Taxi-out vs taxi-in, 10 European airports, 2025\n(movements with 1 min ≤ taxi ≤ 4 h; N = %s)" % f"{c.height:,}")
ax.legend(loc="lower right", fontsize=8); ax.spines[["top","right"]].set_visible(False)
fig.text(0.01,0.01,"Source: PRC Data Challenge 2026 (EUROCONTROL). Aggregates only.", fontsize=7, color="gray")
fig.tight_layout(); fig.savefig(f"{CHARTS}/01_taxi_by_airport.png", dpi=150)
